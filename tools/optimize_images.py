#!/usr/bin/env python3
"""Build assets/img from the untouched originals in assets/gallery.

Run from the project root:  python -I tools/optimize_images.py

Writes <name>-<width>.webp at each width, <name>.jpg as the no-WebP fallback, and
assets/img/manifest.js, which app.js reads for srcset widths, dimensions and placeholder colours.
"""
import glob
import json
import os

from PIL import Image

SRC, OUT = "assets/gallery", "assets/img"
WIDTHS = (480, 960)
WEBP_Q, JPG_Q = 76, 80

# name: (source glob, letterboxed?, rows to keep from the top once any bars are gone)
# The keep values cut the POCO camera watermark (g2, g4, i1) and burned-in venue captions (i3, i4).
PHOTOS = {
    "g1": ("unnamed (1).webp", False, None),
    "g2": ("unnamed (2).webp", False, 680),
    "g3": ("unnamed (3).webp", False, None),
    "g4": ("unnamed (4).webp", False, 680),
    "g5": ("unnamed (5).webp", False, None),
    "g6": ("unnamed (6).webp", False, None),
    "g7": ("unnamed (7).webp", False, None),
    "g8": ("unnamed.webp", False, None),
    "i1": ("531414056_*", True, 318),
    "i2": ("550668140_*", True, None),
    "i3": ("620845251_*", True, 358),
    "i4": ("626657279_*", True, 885),
    "i5": ("630127935_*", True, None),
    "i6": ("642903785_*", True, None),
    "i7": ("649236276_*", True, None),
    # Only small copies of these exist, so they are served at native size in small slots only.
    "t1": ("unnamed (1).jpg", False, None),
    "t2": ("unnamed (2).jpg", False, None),
    "t3": ("unnamed (5).jpg", False, None),
    "t4": ("unnamed (6).jpg", False, None),
    "logo": ("download.jpg", False, None),
}


def trim_bars(im):
    box = im.convert("L").point(lambda p: 255 if p > 22 else 0).getbbox()
    if box and box[3] - box[1] >= im.height * 0.12:
        return im.crop(box)
    return im


def main():
    os.makedirs(OUT, exist_ok=True)
    manifest, total = {}, 0
    for name, (pattern, bars, keep) in PHOTOS.items():
        found = glob.glob(os.path.join(SRC, pattern))
        assert len(found) == 1, f"{name}: expected one source for {pattern}, got {found}"
        im = Image.open(found[0]).convert("RGB")
        if bars:
            im = trim_bars(im)
        if keep:
            assert keep <= im.height, f"{name}: keep {keep} exceeds height {im.height}"
            im = im.crop((0, 0, im.width, keep))

        widths = [w for w in WIDTHS if w < im.width] + [im.width]
        for w in widths:
            path = os.path.join(OUT, f"{name}-{w}.webp")
            size = (w, round(im.height * w / im.width))
            im.resize(size, Image.LANCZOS).save(path, "WEBP", quality=WEBP_Q, method=6)
            total += os.path.getsize(path)
        im.save(os.path.join(OUT, f"{name}.jpg"), "JPEG", quality=JPG_Q, optimize=True, progressive=True)

        r, g, b = im.resize((1, 1), Image.BOX).getpixel((0, 0))
        manifest[name] = {"w": widths, "h": im.height, "c": f"#{r:02x}{g:02x}{b:02x}"}

    with open(os.path.join(OUT, "manifest.js"), "w", encoding="utf8") as f:
        f.write("/* generated by tools/optimize_images.py */\nwindow.IMG=" + json.dumps(manifest, separators=(",", ":")) + ";\n")

    # self-check: every variant opens at its promised width, nothing upscaled, no metadata carried over
    for name, m in manifest.items():
        for w in m["w"]:
            with Image.open(os.path.join(OUT, f"{name}-{w}.webp")) as v:
                assert v.width == w, f"{name}-{w}: width is {v.width}"
                assert not v.getexif(), f"{name}-{w}: metadata survived"
        assert m["w"] == sorted(m["w"]), f"{name}: widths out of order"
    print(f"{len(manifest)} photos, {sum(len(m['w']) for m in manifest.values())} WebP variants, {total // 1024} KB of WebP")
    for name, m in manifest.items():
        print(name, m["w"], f"{m['w'][-1]}x{m['h']}", m["c"],
              " ".join(f"{os.path.getsize(os.path.join(OUT, f'{name}-{w}.webp')) // 1024}KB" for w in m["w"]))


if __name__ == "__main__":
    main()
